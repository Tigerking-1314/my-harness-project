#!/usr/bin/env python3
"""Build site/cities.js, the bundled offline city list (ADR-0007 QST-CITY-LIST = C).

US towns over 1,000 people (GeoNames cities1000, US rows) plus cities over
15,000 everywhere else (GeoNames cities15000, non-US rows). The page finds your
nearest city in this list on your device, so your coordinates never leave it.

Usage (download and unzip both files from https://download.geonames.org/export/dump/ first):
    python3 scripts/build-cities.py path/to/cities1000.txt path/to/cities15000.txt site/cities.js

Output: an ES module (loaded with import(), which the CSP's script-src 'self'
allows; connect-src has no 'self', so a fetch() of a data file would be blocked).
Rows: name|country|US state (empty outside the US)|lat|lon, coordinates to 3 decimals (~100 m).
Data: GeoNames, CC BY 4.0 (credited in the page's Settings).
"""
import datetime
import json
import math
import re
import sys

# GeoNames "geoname" table columns (0-based): 1 name, 4 latitude, 5 longitude,
# 7 feature code, 8 country code, 10 admin1 code
NAME, LAT, LON, FEATURE, COUNTRY, ADMIN1 = 1, 4, 5, 7, 8, 10

# Not towns you can be "in": PPLX = a section of a city, plus historical,
# abandoned and destroyed places.
SKIP_FEATURES = {"PPLX", "PPLH", "PPLQ", "PPLW", "PPLCH"}

# Numbered districts that GeoNames tags as ordinary towns (PPL), e.g. "Paris 04
# Hôtel-de-Ville", "Lyon 03", "Marseille 08 …". Without this, central Paris was
# named "Paris 04 Hôtel-de-Ville" (caught by tests/geo.test.js, 2026-11-24).
DISTRICT_RE = re.compile(r"^(.+?) \d{1,2}(?: |$)")
DISTRICT_KM = 15


def km(a, b):
    rad = math.pi / 180
    h = (math.sin((b[0] - a[0]) * rad / 2) ** 2
         + math.cos(a[0] * rad) * math.cos(b[0] * rad) * math.sin((b[1] - a[1]) * rad / 2) ** 2)
    return 2 * 6371 * math.asin(min(1, math.sqrt(h)))


def drop_numbered_districts(places):
    """places: [(name, country, state, lat, lon)] → without "<City> NN …" rows near <City>."""
    by_name = {}
    for p in places:
        by_name.setdefault((p[0], p[1]), []).append(p)
    kept = []
    for p in places:
        m = DISTRICT_RE.match(p[0])
        parents = by_name.get((m.group(1), p[1]), []) if m else []
        if any(km((p[3], p[4]), (q[3], q[4])) <= DISTRICT_KM for q in parents):
            continue
        kept.append(p)
    return kept


def rows(path, keep):
    with open(path, encoding="utf-8") as f:
        for line in f:
            col = line.rstrip("\n").split("\t")
            if len(col) <= ADMIN1 or not keep(col[COUNTRY]) or col[FEATURE] in SKIP_FEATURES:
                continue
            name = col[NAME].replace("|", " ").strip()
            if not name:
                continue
            state = col[ADMIN1] if col[COUNTRY] == "US" else ""
            yield (name, col[COUNTRY], state, float(col[LAT]), float(col[LON]))


def line(p):
    return f"{p[0]}|{p[1]}|{p[2]}|{p[3]:.3f}|{p[4]:.3f}"


def main(us_source, world_source, out_path):
    us = drop_numbered_districts(list(rows(us_source, lambda cc: cc == "US")))
    world = drop_numbered_districts(list(rows(world_source, lambda cc: cc != "US")))
    body = "\n".join(line(p) for p in us + world)
    header = (
        f"// GENERATED by scripts/build-cities.py on {datetime.date.today().isoformat()}; do not edit by hand.\n"
        f"// ADR-0007: {len(us)} US towns (GeoNames cities1000) + {len(world)} other cities (cities15000).\n"
        "// City data © GeoNames (https://www.geonames.org/), CC BY 4.0.\n"
        "// Rows: name|country|US state|lat|lon — parsed by parseCities() in geo.js.\n"
    )
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(header + "export const CITIES = " + json.dumps(body, ensure_ascii=False) + ";\n")
    print(f"wrote {out_path}: {len(us)} US + {len(world)} world = {len(us) + len(world)} places")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
